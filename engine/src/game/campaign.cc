SpeakerInfo speaker(Speaker s) {
    switch (s) {
        case Speaker::Vira: return {"Вира, старая фонарщица", 0xff8ad2ffu};
        case Speaker::Keeper: return {"Хранитель", 0xffffe8cfu};
        case Speaker::Haze: return {"Мгла", 0xffe09ab5u};
        case Speaker::King: return {"Король Пепла", 0xff8a8ae0u};
        case Speaker::Narrator: return {"", 0xffc0d0d8u};
    }
    return {"", 0xffffffffu};
}

