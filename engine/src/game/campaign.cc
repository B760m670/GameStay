SpeakerInfo speaker(Speaker s) {
    switch (s) {
        case Speaker::Elisey: return {"Елисей, промысловик", 0xff9ad0e8u};
        case Speaker::Player: return {"Приказчик", 0xffffe8cfu};
        case Speaker::Kudeyar: return {"Кудеяр, атаман", 0xff8a9ae0u};
        case Speaker::Voevoda: return {"Тобольский воевода", 0xffa0d8c0u};
        case Speaker::Narrator: return {"", 0xffc0d0d8u};
    }
    return {"", 0xffffffffu};
}

